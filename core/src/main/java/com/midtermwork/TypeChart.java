    public static float multiplier(GameWorld.Element attack,GameWorld.Element primary,GameWorld.Element secondary){
        if(attack==null||primary==null)throw new IllegalArgumentException("Attack and primary types required");
        float value=FACTOR[attack.typeId-1][primary.typeId-1]/100f;
        if(secondary!=null&&secondary!=primary)value*=FACTOR[attack.typeId-1][secondary.typeId-1]/100f;
        return value;
    }
    public static String label(float value){return value==0?"효과 없음":value>=4?"약점 4배":value>=2?"약점 2배":value<=.25f?"반감 0.25배":value<1?"반감 0.5배":"보통 1배";}
